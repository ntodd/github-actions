// Setup renders this file into the target repository. Triggers and permission
// ceilings live there; authorization, execution and recovery remain shared.
export function callerWorkflow({ toolingRepository = "ntodd/github-actions", ref = "main", defaultBranch,
  ciWorkflows, dryRun = true, attachments = false } = {}) {
  if (!/^[\w.-]+\/[\w.-]+$/.test(toolingRepository) || !/^[a-z\d][\w./-]{0,199}$/i.test(ref) || ref.includes("..")
    || typeof defaultBranch !== "string" || !/^[a-z\d][\w./-]{0,199}$/i.test(defaultBranch) || defaultBranch.includes("..")
    || typeof dryRun !== "boolean" || typeof attachments !== "boolean" || !Array.isArray(ciWorkflows) || !ciWorkflows.length || ciWorkflows.length > 50
    || ciWorkflows.some((s) => typeof s !== "string" || !s.trim() || s.length > 100 || /[\x00-\x1f]|\$\{\{/.test(s))) {
    throw new Error("Caller needs a valid shared ref, default branch and explicit CI workflow names");
  }
  const workflows = [...new Set([...ciWorkflows, "factory"])];
  return `name: factory

# Generated by factory setup. Repository settings live in .github/factory.yml.
on:
  issues:
    types: [opened, edited, labeled, unlabeled, closed, reopened]
  issue_comment:
    types: [created, edited, deleted]
  pull_request_target:
    types: [opened, edited, synchronize, closed, reopened, ready_for_review, converted_to_draft, labeled, unlabeled, auto_merge_enabled, auto_merge_disabled]
  pull_request_review:
    types: [submitted, edited, dismissed]
  pull_request_review_comment:
    types: [created, edited, deleted]
  push:
    branches: ${JSON.stringify([defaultBranch])}
  workflow_run:
    workflows: ${JSON.stringify(workflows)}
    types: [completed]
  check_run:
    types: [completed, rerequested]
  status:
  schedule:
    - cron: '17 * * * *'
  workflow_dispatch:
    inputs:
      request:
        description: Internal request; the controller rereads authority from GitHub.
        type: string
        default: ''

permissions: {}

jobs:
  wake-up:
    if: contains(fromJSON('["pull_request_review","pull_request_review_comment"]'), github.event_name)
    permissions:
      contents: read
      actions: write
    uses: ${toolingRepository}/.github/workflows/factory-wakeup.yml@${ref}

  factory:
    if: \${{ !contains(fromJSON('["pull_request_review","pull_request_review_comment"]'), github.event_name) }}
    permissions:
      contents: read
      issues: read
      pull-requests: read
      actions: read
      checks: read
      statuses: read
    uses: ${toolingRepository}/.github/workflows/factory-runtime.yml@${ref}
    with:
      request: \${{ github.event_name == 'workflow_dispatch' && inputs.request || '' }}
      app-id: \${{ vars.AGENT_APP_ID }}
      dry-run: ${dryRun}
    secrets:
      AGENT_APP_PRIVATE_KEY: \${{ secrets.AGENT_APP_PRIVATE_KEY }}
      CLAUDE_CODE_OAUTH_TOKEN: \${{ secrets.CLAUDE_CODE_OAUTH_TOKEN }}
      ANTHROPIC_API_KEY: \${{ secrets.ANTHROPIC_API_KEY }}
      OPENAI_API_KEY: \${{ secrets.OPENAI_API_KEY }}
      SETUP_SECRETS: \${{ secrets.SETUP_SECRETS }}
${attachments ? "      AGENT_ATTACH_TOKEN: ${{ secrets.AGENT_ATTACH_TOKEN }}\n" : ""}`;
}
